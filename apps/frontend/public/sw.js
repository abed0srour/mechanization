/*
  The app shell, kept on the device.

  IndexedDB already means a registration filed with no signal is never lost.
  What it does not mean is that the officer can get *back in*. Every staff route
  is server-rendered on demand, so a browser that discards the tab — which iOS
  Safari and Android Chrome both do under memory pressure, and routinely when
  the phone is locked and another app is opened — reloads it on return, and
  offline that reload fails. The records are safe and the officer is locked out
  with a settlement still to register. This is what closes that gap.

  Deliberately hand-written rather than generated by Workbox: it is one fetch
  handler with three branches, the library would be larger than the thing it
  replaced, and every byte here ships to a phone on the connection this whole
  feature exists because of.

  What is NOT cached, and why it matters more than what is:

    - Anything that is not a GET. A queued registration is the sync queue's
      job; a service worker replaying a POST from a cache would be a second,
      invisible path to registering the same household twice.
    - The API, on any origin. Citizen records carry identity-document numbers,
      home coordinates and residency status; a stale copy of that on a shared
      field tablet is a disclosure, and a stale *fee balance* is a collector
      telling someone they owe the wrong amount.

  What is cached is the shell only. The staff screens are client components
  that fetch their data with a token from `localStorage`, so the HTML held here
  carries no citizen data at all — the municipality's name is the most it
  contains.
*/

/** Bump to retire every cache this worker wrote. */
const VERSION = 'v2';

const SHELL_CACHE = `mechanization-shell-${VERSION}`;
const ASSET_CACHE = `mechanization-assets-${VERSION}`;
const CURRENT = [SHELL_CACHE, ASSET_CACHE];

const OFFLINE_PAGE = '/offline.html';

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const shell = await caches.open(SHELL_CACHE);
      await shell.add(OFFLINE_PAGE);

      /*
        Nothing else is precached here, because nothing else is knowable here.

        The routes worth keeping are `/{tenant}/{locale}/{adminPath}/citizens…`
        and this worker has no idea which municipality it is installed for, let
        alone that municipality's deliberately-obscure admin segment. The page
        knows all three, so it tells us — see the `warm` message below.
      */
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const name of await caches.keys()) {
        if (name.startsWith('mechanization-') && !CURRENT.includes(name)) {
          await caches.delete(name);
        }
      }
      // Take over open tabs now rather than on their next load: an officer who
      // installed the app mid-session should not have to reload to be covered.
      await self.clients.claim();
    })(),
  );
});

/**
 * Every `/_next/static/…` path a page's HTML actually references.
 *
 * Not a DOM parser — service workers do not reliably have one — a single
 * global regex over the raw response text. Next emits these as ordinary
 * `href="…"` / `src="…"` attributes (plus, in dev, a `?v=` cache-busting
 * query the production build does not carry), so matching up to the next
 * quote or backslash catches every shape without caring which tag it sat
 * inside.
 *
 * Deliberately *not* excluded: `)`. A route group segment — this app has
 * `(protected)` on every admin path — puts a literal parenthesis in the URL
 * itself, and stopping there truncated the match to a path Next never served,
 * silently dropping every asset the page-specific chunk needed.
 *
 * Deliberately excluded: `\`. The same href reappears, escaped, inside the
 * inline RSC payload Next embeds as a JSON string (`self.__next_f.push(...)`)
 * — without this, the match runs on past that escaped quote and produces a
 * second, malformed copy of the URL with a trailing backslash that can only
 * ever fail to fetch.
 */
function staticAssetUrlsIn(html) {
  return [...new Set(html.match(/\/_next\/static\/[^\s"'\\]+/g) ?? [])];
}

/**
 * Routes to fetch and keep, sent by the page once it knows them.
 *
 * Only ever the two screens the field work runs through — the entry form and
 * the registry that lists what is still queued. Warming them means an officer
 * whose tab was discarded can relaunch cold, with no signal, straight into the
 * form. Widening this list would cache more authenticated HTML for no offline
 * benefit, so it stays at two.
 *
 * Caching the document is not enough on its own. A service worker does not
 * control the page that registers it until that page's *next* load — every
 * script and stylesheet the first visit ever made was already fetched
 * straight from the network, past the worker entirely — so without this, the
 * HTML lands on a discarded-tab relaunch with no CSS and no JavaScript behind
 * it: a page of plain, unstyled links that respond to nothing. Reading the
 * cached document back out for the paths it references, and fetching each of
 * those in turn, is what a browser's own navigation would have triggered
 * anyway; this only does it once, up front, instead of leaving it to chance.
 */
self.addEventListener('message', (event) => {
  const data = event.data;
  if (!data || data.type !== 'warm' || !Array.isArray(data.routes)) return;

  event.waitUntil(
    (async () => {
      const shell = await caches.open(SHELL_CACHE);
      const assets = await caches.open(ASSET_CACHE);
      const assetUrls = new Set();

      await Promise.all(
        data.routes.map(async (route) => {
          try {
            // `reload` so warming refreshes a stale shell rather than
            // re-storing whatever the HTTP cache happens to be holding.
            const response = await fetch(route, { cache: 'reload', credentials: 'same-origin' });
            if (!response.ok) return;

            // Read the asset list from a clone — the original body is still
            // needed whole for the cache entry below.
            for (const url of staticAssetUrlsIn(await response.clone().text())) {
              assetUrls.add(url);
            }
            await shell.put(route, response);
          } catch {
            // Offline, or the route 404s on this deploy. Either way the
            // previous copy stands and the officer is no worse off.
          }
        }),
      );

      await Promise.all(
        [...assetUrls].map(async (url) => {
          // Content-hashed and immutable: an entry already on disk is still
          // correct, and re-fetching it would only cost the officer data.
          if (await assets.match(url)) return;
          try {
            const response = await fetch(url);
            if (response.ok) await assets.put(url, response);
          } catch {
            // One missing chunk degrades the shell; it does not sink it.
          }
        }),
      );
    })(),
  );
});

/**
 * Whether a route is one this worker keeps a copy of.
 *
 * The same two screens `warm` fetches, matched by shape so the worker needs to
 * know neither the municipality nor its admin segment. Everything else is
 * served from the network and, offline, falls through to the offline page.
 *
 * The alternative — keeping every admin page anyone navigates to — is
 * unbounded in the one place it matters: `citizens/{id}` is a distinct URL per
 * household, so a busy counter would write a cache entry per citizen looked up
 * and never reclaim any of them. None of those pages is any use offline
 * anyway; they render from an API this worker deliberately never caches.
 */
function isShellRoute(pathname) {
  return /\/citizens(\/new)?\/?$/.test(pathname);
}

/** Content-hashed and immutable: if it is in the cache it is correct. */
async function cacheFirst(request) {
  const cache = await caches.open(ASSET_CACHE);
  const hit = await cache.match(request);
  if (hit) return hit;

  const response = await fetch(request);
  if (response.ok) await cache.put(request, response.clone());
  return response;
}

/**
 * The offline fallback page, its two dead-end links resolved to this
 * municipality's actual admin path.
 *
 * `offline.html` is one static file shared by every tenant and cached once
 * at install time, with no way to know then which municipality a future
 * stranded navigation will belong to. This fills that in — from the failed
 * request's own URL, which always carries `/{tenant}/{locale}/{adminPath}`
 * as its first three segments — in the worker's own script rather than an
 * inline `<script>` on the page, which this app's Content-Security-Policy
 * (a per-request nonce plus `strict-dynamic`, no `unsafe-inline`) would
 * silently refuse to run: a cached static file can never carry a nonce that
 * matches whatever the policy generates for a request made an hour later.
 *
 * Falls back to leaving the placeholders in place — a dead link, not a
 * broken page — for the one pathname shape that cannot happen from inside
 * this app: fewer than three segments, which the middleware itself already
 * redirects to a 404 before any real screen is reached.
 */
async function offlinePageFor(pathname) {
  const cache = await caches.open(SHELL_CACHE);
  const page = await cache.match(OFFLINE_PAGE);
  if (!page) return undefined;

  const segments = pathname.split('/').filter(Boolean);
  if (segments.length < 3) return page;

  const base = `/${segments.slice(0, 3).join('/')}`;
  const html = (await page.text())
    .replaceAll('__CITIZENS_NEW__', `${base}/citizens/new`)
    .replaceAll('__CITIZENS_LIST__', `${base}/citizens`);

  return new Response(html, { headers: page.headers });
}

/**
 * The network decides, and the cache catches it when the network cannot.
 *
 * Network-first rather than cache-first for documents, so a deployed fix
 * reaches the field the next time anyone has signal. A service worker that
 * preferred its cache would pin every device to the build that installed it,
 * which is the failure mode that makes people distrust offline apps.
 */
async function networkFirst(request, { fallback, store = true } = {}) {
  const cache = await caches.open(SHELL_CACHE);

  try {
    const response = await fetch(request);
    if (store && response.ok) await cache.put(request, response.clone());
    return response;
  } catch (error) {
    /*
      `ignoreVary`: Next varies its responses on `RSC` and the router state
      tree, so a strict match fails for a request that differs only in headers
      the cached copy would have served perfectly well.
    */
    const hit = await cache.match(request, { ignoreVary: true });
    if (hit) return hit;
    if (fallback) {
      // A callback rather than a fixed cache key: the offline page is not a
      // static asset here, it is one built fresh per request — see
      // `offlinePageFor` above.
      const page = await fallback();
      if (page) return page;
    }
    throw error;
  }
}

self.addEventListener('fetch', (event) => {
  const { request } = event;

  // A POST is the queue's business, never this worker's. See the header note.
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // The API is a separate origin in every deployment that matters, but check
  // the path too: nothing under /api is ever served from a cache.
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return;

  if (url.pathname.startsWith('/_next/static/')) {
    event.respondWith(cacheFirst(request));
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith(
      networkFirst(request, {
        fallback: () => offlinePageFor(url.pathname),
        store: isShellRoute(url.pathname),
      }),
    );
    return;
  }

  /*
    Next's client-side navigations fetch a payload rather than a document, so
    without this «حفظ» → registry → «تسجيل مواطن جديد» fails offline even
    though both screens are cached.

    These are cached as they are visited rather than warmed: the payload URL
    carries a build-scoped hash this worker cannot construct. No fallback
    either — when the payload is genuinely absent, letting the fetch fail is
    what makes Next fall back to a full navigation, which the branch above then
    serves from the shell cache.
  */
  if (request.headers.has('RSC')) {
    event.respondWith(networkFirst(request, { store: isShellRoute(url.pathname) }));
  }
});
